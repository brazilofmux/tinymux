// FCVT.{W,WU,L,LU}.D conformance
// ---------------------------------------------------------------
//
// This is deliberately NOT a differential test against the DBT.  The
// differential fuzzer in this directory compares the interpreter with the
// translator and reports where they disagree, which by construction cannot
// see anything they get wrong in the same way -- and two such bugs lived
// here: every convert truncated instead of honouring the rounding mode, and
// NaN converted to 0 rather than the destination type's maximum in the
// unsigned forms.  Both routes agreed, so the fuzzer called it clean.
//
// The expected values below therefore come from qemu-riscv64 running the
